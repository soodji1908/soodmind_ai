'use client';

import { useState, type FormEvent } from 'react';
import { Bot, MessageCircle, Send, X } from 'lucide-react';
import { Button } from '@/components/ui/button';

type Message = { role: 'user' | 'assistant'; content: string };

export function AIAssistant() {
  const [open, setOpen] = useState(false);
  const [messages, setMessages] = useState<Message[]>([]);
  const [input, setInput] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');

  async function send(event: FormEvent) {
    event.preventDefault();
    const content = input.trim();
    if (!content || busy) return;
    const next: Message[] = [...messages, { role: 'user', content }];
    setMessages(next); setInput(''); setBusy(true); setError('');
    try {
      const response = await fetch('/api/assistant/chat', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ messages: next }) });
      const data = await response.json();
      if (!response.ok) throw new Error(data.message || 'Assistant request failed.');
      setMessages([...next, { role: 'assistant', content: data.answer }]);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Assistant request failed.');
    } finally { setBusy(false); }
  }

  return <div className="fixed bottom-5 right-5 z-50">
    {open && <section className="mb-3 flex h-[min(560px,75vh)] w-[min(380px,calc(100vw-2rem))] flex-col overflow-hidden rounded-2xl border bg-background shadow-2xl">
      <header className="flex items-center justify-between border-b bg-primary px-4 py-3 text-primary-foreground"><div className="flex items-center gap-2"><Bot className="h-5 w-5"/><div><p className="font-semibold">EstateMind AI</p><p className="text-xs opacity-80">AI-powered assistant</p></div></div><button aria-label="Close assistant" onClick={() => setOpen(false)}><X className="h-5 w-5"/></button></header>
      <div className="flex-1 space-y-3 overflow-y-auto p-3">{messages.length === 0 && <p className="rounded-xl bg-muted p-3 text-sm text-muted-foreground">Ask about property workflows, resumes, hiring, or how to use EstateMind. Answers are generated by your configured AI provider.</p>}{messages.map((message, index) => <div key={index} className={`max-w-[90%] whitespace-pre-wrap rounded-xl p-3 text-sm ${message.role === 'user' ? 'ml-auto bg-primary text-primary-foreground' : 'bg-muted'}`}>{message.content}</div>)}{busy && <p className="text-sm text-muted-foreground">Thinking…</p>}{error && <p role="alert" className="rounded-lg bg-red-50 p-2 text-xs text-red-700 dark:bg-red-950 dark:text-red-200">{error}</p>}</div>
      <form onSubmit={send} className="flex gap-2 border-t p-3"><input value={input} onChange={(e) => setInput(e.target.value)} maxLength={4000} placeholder="Ask EstateMind AI…" className="h-10 min-w-0 flex-1 rounded-lg border bg-background px-3 text-sm"/><Button type="submit" size="icon" disabled={busy || !input.trim()} aria-label="Send message"><Send className="h-4 w-4"/></Button></form>
    </section>}
    <Button onClick={() => setOpen((v) => !v)} className="h-12 rounded-full px-5 shadow-lg"><MessageCircle className="mr-2 h-5 w-5"/>{open ? 'Close AI' : 'Ask AI'}</Button>
  </div>;
}
